const versions: Readonly<Record<Engine, string>> = {
  redis: "8.10.2",
  valkey: "9.1.2",
  dragonfly: "2.0.2",
  keydb: "6.3.4",
  redict: "7.3.6",
  garnet: "2.2.4",
  kvrocks: "2.17.0",
};

export const expectations = (engine: Engine, version: string) => {
  if (versions[engine] !== version) throw new Error("Unreviewed engine/version conformance target");
  const unavailable = new Set(missing[engine]);
  if (engine !== "redis") unavailable.add("ARSCAN");
  if (["keydb", "dragonfly", "garnet"].includes(engine)) {
    for (const operation of [
      "LOAD",
      "LIST",
      "STATS",
      "DELETE",
      "DUMP",
      "RESTORE",
      "FLUSH",
      "HELP",
      "KILL",
    ])
      unavailable.add(`FUNCTION ${operation}`);
    unavailable.add("FCALL_RO");
  }
  if (engine === "keydb") unavailable.add("EVALSHA_RO");
  if (engine === "garnet") {
    for (const operation of ["CREATE", "CREATECONSUMER", "DELCONSUMER", "DESTROY", "SETID", "HELP"])
      unavailable.add(`XGROUP ${operation}`);
    for (const operation of ["STREAM", "CONSUMERS", "GROUPS", "HELP"])
      unavailable.add(`XINFO ${operation}`);
  }

  const families: ReadonlyArray<readonly [ReadonlyArray<Engine>, ReadonlyArray<string>]> = [
    [
      ["dragonfly", "kvrocks"],
      [
        "JSON.SET",
        "JSON.GET",
        "JSON.TYPE",
        "JSON.OBJLEN",
        "JSON.ARRLEN",
        "JSON.ARRAPPEND",
        "JSON.NUMINCRBY",
        "JSON.TOGGLE",
        "JSON.DEL",
        "FT.CREATE",
        "FT.SEARCH",
        "FT._LIST",
        "FT.INFO",
        "FT.DROPINDEX",
        "BF.RESERVE",
        "BF.ADD",
        "BF.EXISTS",
        "BF.MEXISTS",
      ],
    ],
    [
      ["kvrocks"],
      [
        "BF.CARD",
        "TDIGEST.CREATE",
        "TDIGEST.ADD",
        "TDIGEST.MIN",
        "TDIGEST.MAX",
        "TS.CREATE",
        "TS.ADD",
        "TS.GET",
      ],
    ],
    [
      ["dragonfly"],
      [
        "CF.RESERVE",
        "CF.ADD",
        "CF.EXISTS",
        "CF.DEL",
        "CMS.INITBYDIM",
        "CMS.INCRBY",
        "CMS.QUERY",
        "TOPK.RESERVE",
        "TOPK.ADD",
        "TOPK.QUERY",
      ],
    ],
    [
      ["redis", "garnet"],
      ["VADD", "VCARD", "VEMB"],
    ],
  ];
  for (const [providers, commands] of families) {
    if (!providers.includes(engine)) for (const name of commands) unavailable.add(name);
  }
  if (engine === "kvrocks") unavailable.add("FUNCTION STATS");
  if (["garnet", "kvrocks"].includes(engine)) unavailable.add("MODULE LIST");

  return { engine, version, unavailable };
};
export type Expectations = ReturnType<typeof expectations>;
